-- Cadastro base (itens genéricos) e ligação de cada produto dos mercados a um item base.
create table if not exists item_base (
  id bigint generated always as identity primary key,
  termo text not null unique,                 -- palavras-chave normalizadas: 'feijao carioca'
  nome text not null,                         -- como aparece no app: 'Feijão carioca'
  exclusoes text[] not null default '{}',     -- palavras que tiram o produto do item ('triturado', 'capsula')
  ativo boolean not null default true
);
alter table item_base enable row level security;
drop policy if exists leitura on item_base;
create policy leitura on item_base for select using (true);

alter table produto add column if not exists item_base_id bigint references item_base(id);
-- regra = ligado automaticamente; admin = decidido no admin (a regra não mexe mais); sem = nenhum item base serviu
alter table produto add column if not exists item_base_origem text check (item_base_origem in ('regra','admin','sem'));
create index if not exists produto_item_base on produto (item_base_id);
create index if not exists produto_item_base_origem on produto (item_base_origem);

